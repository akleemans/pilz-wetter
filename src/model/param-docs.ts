/**
 * Renders the parameter reference for MODEL.md from `PARAMS`, so the
 * documentation cannot drift from the code (params.test.ts checks it).
 */

import { PARAM_GROUPS, PARAM_KEYS, PARAMS, type ParamSpec } from './params.ts';

export const DOCS_START = '<!-- params:start (generated by `bun run docs:params`) -->';
export const DOCS_END = '<!-- params:end -->';

const formatValue = (spec: ParamSpec) =>
  typeof spec.default === 'number'
    ? String(spec.default)
    : spec.items && spec.default.length > 2
      ? spec.default.map((v, i) => `${spec.items![i]}: ${v}`).join(', ')
      : `[${spec.default.join(', ')}]`;

const escape = (text: string) => text.replaceAll('|', String.raw`\|`);

export function renderParamDocs(): string {
  const sections = Object.entries(PARAM_GROUPS).map(([group, title]) => {
    const rows = PARAM_KEYS.filter((key) => PARAMS[key].group === group).map((key) => {
      const spec: ParamSpec = PARAMS[key];
      return `| \`${key}\` | ${escape(spec.label)} | ${formatValue(spec)} | ${spec.unit ?? ''} | ${escape(spec.description)} |`;
    });
    return [
      `#### ${title}`,
      '',
      '| Parameter | Bezeichnung | Standard | Einheit | Beschreibung |',
      '|---|---|---|---|---|',
      ...rows,
    ].join('\n');
  });
  return [DOCS_START, '', ...sections.join('\n\n').split('\n'), '', DOCS_END].join('\n');
}

/** `document` with the generated block replaced (or appended if missing). */
export function updateParamDocs(document: string): string {
  const start = document.indexOf(DOCS_START);
  const end = document.indexOf(DOCS_END);
  if (start < 0 || end < start) {
    return `${document.trimEnd()}\n\n${renderParamDocs()}\n`;
  }
  return document.slice(0, start) + renderParamDocs() + document.slice(end + DOCS_END.length);
}
